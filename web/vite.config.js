import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

export default defineConfig({
  plugins: [react()],
  server: {
    port: 5173,
    // Proxying /api in dev means the browser sees a same-origin request, so
    // CORS is a non-issue locally. The API still enforces CORS for deployed
    // origins, where the SPA and API are on different hosts.
    proxy: {
      '/api': {
        target: process.env.VITE_API_PROXY_TARGET ?? 'http://localhost:4000',
        changeOrigin: true,
      },
    },
  },
});
